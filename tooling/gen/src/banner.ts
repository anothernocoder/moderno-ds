import { basename, extname } from "node:path";

/** How to turn one line of text into a comment, per file type. */
const COMMENT_BY_FILE_TYPE: Record<string, (text: string) => string> = {
  ".gitattributes": (text) => `# ${text}`,
  ".ts": (text) => `// ${text}`,
  ".tsx": (text) => `// ${text}`,
  ".js": (text) => `// ${text}`,
  ".css": (text) => `/* ${text} */`,
  ".md": (text) => `<!-- ${text} -->`,
  ".svelte": (text) => `<!-- ${text} -->`,
};

/** The banner's words, before they are put in a file's own syntax. */
function bannerText(aggregatorName: string, source: string): string {
  return `Generated by pnpm gen (${aggregatorName}) from ${source}. Do not edit by hand.`;
}

/**
 * The first line of every generated file that has a comment syntax: who wrote
 * it, from what, and that a hand edit is lost (and fails `pnpm gen --check`).
 */
export function generatedBanner(aggregatorName: string, source: string, output: string): string {
  const fileType = extname(output) || basename(output);
  const comment = COMMENT_BY_FILE_TYPE[fileType];
  if (!comment) {
    throw new Error(
      `pnpm gen: no comment syntax for "${output}"; add its file type to COMMENT_BY_FILE_TYPE`,
    );
  }
  return comment(bannerText(aggregatorName, source));
}

/**
 * A generated file: the aggregator's body under its banner. JSON has no
 * comments, so a JSON body must be an object and the banner becomes its first
 * property, `$comment`.
 */
export function withGeneratedBanner(
  aggregatorName: string,
  source: string,
  output: string,
  body: string,
): string {
  if (extname(output) !== ".json") {
    return `${generatedBanner(aggregatorName, source, output)}\n${body}`;
  }
  const document = JSON.parse(body) as unknown;
  if (typeof document !== "object" || document === null || Array.isArray(document)) {
    throw new Error(`pnpm gen: "${output}" must be a JSON object to carry the banner`);
  }
  const bannered = { $comment: bannerText(aggregatorName, source), ...document };
  return `${JSON.stringify(bannered, null, 2)}\n`;
}
