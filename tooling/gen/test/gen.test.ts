import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { afterEach, beforeEach, describe, expect, it } from "vitest";
import type { Aggregator } from "../src/aggregator.ts";
import gitattributes from "../src/aggregators/gitattributes.ts";
import { generatedBanner, withGeneratedBanner } from "../src/banner.ts";
import {
  discoverAggregators,
  findStaleFiles,
  renderGeneratedFiles,
  writeGeneratedFiles,
  type NamedAggregator,
} from "../src/gen.ts";

const aggregatorsDir = fileURLToPath(new URL("../src/aggregators", import.meta.url));

/** A stand-in for a later ticket's aggregator: one generated barrel. */
const barrel: NamedAggregator = {
  name: "barrel",
  aggregator: {
    output: "packages/example/src/generated.ts",
    source: "packages/example/src/parts/*.ts",
    generate: () => 'export * from "./parts/button.ts";\n',
  } satisfies Aggregator,
};

const proof: NamedAggregator = { name: "gitattributes", aggregator: gitattributes };

let root: string;
beforeEach(() => {
  root = mkdtempSync(join(tmpdir(), "moderno-gen-"));
});
afterEach(() => {
  rmSync(root, { recursive: true, force: true });
});

describe("discoverAggregators", () => {
  it("finds the proof aggregator in src/aggregators/ without a list", async () => {
    const found = await discoverAggregators(aggregatorsDir);
    expect(found.map(({ name }) => name)).toContain("gitattributes");
  });

  it("loads every module in a folder, sorted by name", async () => {
    const aggregator = (output: string) =>
      `export default { output: "${output}", source: "x/*", generate: () => "" };\n`;
    writeFileSync(join(root, "zeta.ts"), aggregator("z.md"));
    writeFileSync(join(root, "alpha.ts"), aggregator("a.md"));

    const found = await discoverAggregators(root);
    expect(found.map(({ name, aggregator }) => [name, aggregator.output])).toEqual([
      ["alpha", "a.md"],
      ["zeta", "z.md"],
    ]);
  });

  it("rejects a module that does not default-export an aggregator", async () => {
    writeFileSync(join(root, "broken.ts"), "export default { output: 'x.md' };\n");
    await expect(discoverAggregators(root)).rejects.toThrow(/broken\.ts must default-export/);
  });
});

describe("renderGeneratedFiles", () => {
  it("prefixes each body with a banner naming the aggregator and its sources", async () => {
    const [file] = await renderGeneratedFiles([barrel], root);
    expect(file).toEqual({
      path: "packages/example/src/generated.ts",
      content:
        "// Generated by pnpm gen (barrel) from packages/example/src/parts/*.ts. Do not edit by hand.\n" +
        'export * from "./parts/button.ts";\n',
    });
  });

  it("writes .gitattributes from every aggregator's declared output, itself included", async () => {
    const files = await renderGeneratedFiles([proof, barrel], root);
    expect(files.find(({ path }) => path === ".gitattributes")?.content).toBe(
      "# Generated by pnpm gen (gitattributes) from tooling/gen/src/aggregators/*.ts. Do not edit by hand.\n" +
        ".gitattributes linguist-generated=true\n" +
        "packages/example/src/generated.ts linguist-generated=true\n",
    );
  });

  it("refuses two aggregators that write the same file", async () => {
    await expect(renderGeneratedFiles([barrel, { ...barrel, name: "copy" }], root)).rejects.toThrow(
      /more than one aggregator writes packages\/example\/src\/generated\.ts/,
    );
  });
});

describe("generatedBanner", () => {
  it.each([
    [".gitattributes", "# "],
    ["a/b.ts", "// "],
    ["a/b.css", "/* "],
    ["a/b.md", "<!-- "],
    ["a/B.svelte", "<!-- "],
  ])("comments the banner in %s's own syntax", (output, opener) => {
    expect(generatedBanner("name", "src/*", output).startsWith(opener)).toBe(true);
  });

  it("refuses a file type it cannot comment", () => {
    expect(() => generatedBanner("name", "src/*", "config.yaml")).toThrow(/no comment syntax/);
  });
});

describe("withGeneratedBanner", () => {
  it("puts the banner on the line above the body", () => {
    expect(withGeneratedBanner("name", "src/*", "a/b.css", "a {}\n")).toBe(
      "/* Generated by pnpm gen (name) from src/*. Do not edit by hand. */\na {}\n",
    );
  });

  it("makes the banner a JSON object's first property, $comment", () => {
    expect(withGeneratedBanner("name", "src/*", "a/b.json", '{"items":[]}')).toBe(
      "{\n" +
        '  "$comment": "Generated by pnpm gen (name) from src/*. Do not edit by hand.",\n' +
        '  "items": []\n' +
        "}\n",
    );
  });

  it("refuses a JSON body that is not an object", () => {
    expect(() => withGeneratedBanner("name", "src/*", "a/b.json", "[]")).toThrow(
      /must be a JSON object/,
    );
  });
});

describe("pnpm gen --check", () => {
  it("passes when every committed file is what pnpm gen writes", async () => {
    const files = await renderGeneratedFiles([proof, barrel], root);
    writeGeneratedFiles(files, root);
    expect(findStaleFiles(files, root)).toEqual([]);
  });

  it("fails on a file that was never generated", async () => {
    const files = await renderGeneratedFiles([proof, barrel], root);
    expect(findStaleFiles(files, root)).toEqual([
      ".gitattributes",
      "packages/example/src/generated.ts",
    ]);
  });

  it("fails on a stale file: its sources changed since it was generated", async () => {
    writeGeneratedFiles(await renderGeneratedFiles([proof], root), root);

    // A new aggregator lands: .gitattributes must now list its output too.
    const files = await renderGeneratedFiles([proof, barrel], root);
    expect(findStaleFiles(files, root)).toEqual([
      ".gitattributes",
      "packages/example/src/generated.ts",
    ]);
  });

  it("fails on a hand-edited file", async () => {
    const files = await renderGeneratedFiles([proof, barrel], root);
    writeGeneratedFiles(files, root);
    const edited = join(root, ".gitattributes");
    writeFileSync(edited, readFileSync(edited, "utf8") + "*.png binary\n");

    expect(findStaleFiles(files, root)).toEqual([".gitattributes"]);
  });
});
